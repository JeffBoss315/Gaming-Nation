-- ============================================================
-- GAMING NATION — driver to driver messaging
--
-- Run this in Supabase -> SQL Editor. Idempotent, like the rest of
-- supabase/: safe on a fresh project, safe to re-run, and it drops
-- nothing.
--
-- WHY THIS FILE EXISTS
--
-- Messages were the last thing on the platform still talking to
-- fleet-server.js. Everything else moved to Supabase, so a driver
-- who opened Messages on the website was told
--
--   "Messages need the company service. Start it with npm run
--    service, or set its address in Settings."
--
-- which is a true sentence about a service nobody outside the
-- office runs. The conversation could not leave one machine.
--
-- WHAT WAS ALREADY THERE
--
-- The live project (sfzeauvkguywidrqjntk) was read on 2026-09-08
-- and already had, by hand:
--
--   conversations               (id bigint, created_at, updated_at)
--   conversation_participants   (conversation_id bigint, driver_id uuid, joined_at)
--   conversation_members        (conversation_id bigint, user_id uuid, joined_at)
--   messages                    (id bigint, conversation_id bigint,
--                                sender_id uuid, message text,
--                                read_at, created_at)
--
-- Note conversation_participants.driver_id is a **uuid**, not a
-- driver code and not drivers.id. It is auth.users.id. The name
-- says driver and the type says auth user; this file goes with the
-- type, because that is what the rows actually hold.
--
-- conversation_members is the same table under a second name —
-- two passes at the same idea. This file treats
-- conversation_participants as the real one, copies anything in
-- conversation_members across, and leaves that table alone.
-- Dropping a table with rows in it is not something a migration
-- should decide on its own.
--
-- WHAT WAS MISSING, AND WHY EACH ONE IS SILENT
--
--   * No row level security policies. With RLS on and no policy,
--     every select is a SUCCESSFUL query returning zero rows —
--     indistinguishable from "nobody has messaged you".
--   * Not in the supabase_realtime publication. A subscription
--     reports SUBSCRIBED and then stays quiet for ever.
--   * No way for the browser to open a conversation. Creating one
--     means inserting a participant row for the OTHER person,
--     which no honest policy can allow. That is what the
--     SECURITY DEFINER functions below are for.
--
-- THE SHAPE THE CLIENT TALKS IN
--
-- script.js is keyed on the GMN driver code ("GMN001") in 213
-- places. The tables are keyed on auth uuids. Rather than teach
-- the browser to translate — which it cannot do anyway, because a
-- plain driver may only read their own drivers row — every
-- function here takes and returns driver codes and does the
-- translation in the database.
-- ============================================================


