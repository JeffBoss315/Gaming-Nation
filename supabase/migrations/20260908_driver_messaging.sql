grant execute on function public.dm_directory()                     to authenticated;


-- ------------------------------------------------------------
-- 6. Realtime
--
-- Without this the client polls and a message takes up to the
-- length of the poll to appear, which is the difference between a
-- conversation and a form. replica identity full so an UPDATE —
-- which is what removing a message is — carries the old row too.
-- ------------------------------------------------------------

alter table public.messages                  replica identity full;
alter table public.conversations             replica identity full;
alter table public.conversation_participants replica identity full;

do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public' and tablename = 'conversation_participants'
  ) then
    alter publication supabase_realtime add table public.conversation_participants;
  end if;
end $$;


-- ------------------------------------------------------------
-- 7. Photos and files
--
-- A private bucket. The path is <conversation id>/<random>-<name>,
-- and the policies below resolve that first segment back to a
-- conversation and ask whether this driver is in it — so a signed
-- URL is issued only to somebody who can already read the message
-- the file is attached to.
--
-- storage.objects has RLS of its own; these are policies on that
-- table, not on the bucket row.
-- ------------------------------------------------------------

-- The conversation a storage path belongs to, or null if the name
-- is not shaped like one. A plain cast would raise on a path with
-- a non-numeric first segment and take the whole policy check down
-- with it.
create or replace function public.dm_path_conversation(object_name text)
returns bigint
language plpgsql
immutable
as $$
declare
  head text := split_part(coalesce(object_name, ''), '/', 1);
begin
  if head ~ '^\d+$' then
    return head::bigint;
  end if;
  return null;
end $$;

grant execute on function public.dm_path_conversation(text) to authenticated;

-- Wrapped, and this is the one place in this file that is.
--
-- storage.buckets and storage.objects are not ours; on some projects the
-- role running the SQL editor cannot write policies on them. The SQL
-- editor runs this whole file as one transaction, so an error here would
-- roll back the tables, the policies and the functions above it — and
-- the message on screen would be about storage, which is the least
-- important thing in the file.
--
-- So it is allowed to fail. Text messaging works without it; sending a
-- photo does not, and the client already says so in those words when the
-- bucket is missing.
do $$
begin
  insert into storage.buckets (id, name, public, file_size_limit)
  values ('dm', 'dm', false, 26214400)
  on conflict (id) do nothing;

  drop policy if exists "Members read conversation files" on storage.objects;
  create policy "Members read conversation files"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'dm'
    and public.dm_is_member(public.dm_path_conversation(name))
  );

  drop policy if exists "Members attach files" on storage.objects;
  create policy "Members attach files"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'dm'
    and owner = auth.uid()
    and public.dm_is_member(public.dm_path_conversation(name))
  );

  drop policy if exists "Senders remove their own files" on storage.objects;
  create policy "Senders remove their own files"
  on storage.objects for delete to authenticated
  using (bucket_id = 'dm' and owner = auth.uid());

exception when others then
  raise notice 'Attachments are not set up: %. Messages still work; photos '
    'and files will not until the dm bucket and its policies exist. '
    'Create the bucket in Storage and re-run this section.', sqlerrm;
end $$;


